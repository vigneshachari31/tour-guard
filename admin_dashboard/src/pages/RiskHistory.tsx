import { useState } from "react";
import { useResource, date } from "../hooks";
import type { Page, Risk } from "../types";
import { Badge, Heading, Notice, Table, Pager } from "../components/UI";
export default function RiskHistory() {
  const [offset, setOffset] = useState(0);
  const data = useResource<Page<Risk>>(
    `/risk-assessments?offset=${offset}`,
    30000,
  );
  return (
    <>
      <Heading eyebrow="ASSESSMENT TRANSPARENCY" title="Route risk history" />
      <Notice error={data.error} />
      <p className="muted">
        Recorded heuristic assessments and their factor explanations. Numeric ML
        scores are not generated by the current route engine.
      </p>
      <section className="panel">
        <Table
          loading={data.loading && !data.data}
          rows={data.data?.items ?? []}
          columns={[
            {
              title: "Assessment",
              render: (r) => (
                <>
                  #{r.id}
                  <small>Trip {r.trip_id ?? "not linked"}</small>
                </>
              ),
            },
            { title: "Risk", render: (r) => <Badge>{r.risk_level}</Badge> },
            {
              title: "Route",
              render: (r) =>
                `${(r.distance_meters / 1000).toFixed(1)} km · ${Math.ceil(r.duration_seconds / 60)} min`,
            },
            {
              title: "Hazards / weather",
              render: (r) => (
                <>
                  {r.hazards_count} hazards
                  <small>
                    Weather {r.weather_used ? "included" : "not included"}
                  </small>
                </>
              ),
            },
            {
              title: "Factors & limits",
              render: (r) => (
                <details>
                  <summary>View explanation</summary>
                  {r.reasons.map((s, i) => (
                    <p key={"r" + i}>{s}</p>
                  ))}
                  {r.limitations.map((s, i) => (
                    <p className="muted" key={"l" + i}>
                      {s}
                    </p>
                  ))}
                </details>
              ),
            },
            { title: "Evaluated", render: (r) => date(r.created_at) },
          ]}
        />
        <Pager
          total={data.data?.total ?? 0}
          offset={offset}
          setOffset={setOffset}
        />
      </section>
    </>
  );
}
