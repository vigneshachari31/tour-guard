import { test, expect } from "@playwright/test";

test("Live tourist movement and completion synchronize without reload", async ({page, request}) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("/admin/");
  await page.getByLabel("Email address").fill("admin-e2e@example.com");
  await page.getByLabel("Password", {exact:true}).fill("isolated-browser-password");
  await page.getByRole("button", {name:"Sign in", exact:true}).click();
  await page.getByRole("link", {name:"Trip Monitoring", exact:true}).click();
  await expect(page.getByText("Live tracking connected", {exact:true})).toBeVisible();
  const row = page.getByRole("row").filter({hasText:"Tracking Source"});
  await expect(row).toContainText("IN_PROGRESS");
  await row.getByRole("button", {name:"View route"}).click();
  await expect(page.locator(".rescue-map")).toBeVisible();
  await expect(page.locator(".leaflet-overlay-pane path").first()).toBeVisible();
  const adminLogin = await request.post("/api/v1/admin/auth/login", {data:{email:"admin-e2e@example.com",password:"isolated-browser-password"}});
  const admin = await adminLogin.json();
  const active = await request.get("/api/v1/admin/active-trips", {headers:{Authorization:`Bearer ${admin.access_token}`}});
  const trip = (await active.json()).items.find((t: {source_name:string}) => t.source_name === "Tracking Source");
  expect(trip).toBeTruthy();
  const login = await request.post("/api/v1/auth/login", {data:{email:"tourist-e2e@example.com", password:"isolated-browser-password"}});
  const tourist = await login.json();
  const headers = {Authorization:`Bearer ${tourist.access_token}`};
  const move = await request.post(`/api/v1/trips/${trip.id}/locations`, {headers,data:{latitude:19.045,longitude:72.855}});
  expect(move.status()).toBe(201);
  await expect(row).not.toContainText("Awaiting GPS");
  await expect(page.locator('.leaflet-overlay-pane path[fill="#1EAA55"]')).toHaveCount(1);
  await page.screenshot({path:"test-results/tracking-moving.png",fullPage:true});
  const finish = await request.post(`/api/v1/trips/${trip.id}/locations`, {headers,data:{latitude:19.05,longitude:72.86}});
  expect(finish.status()).toBe(201);
  await expect(row.locator(".badge-completed")).toHaveText("COMPLETED");
  await expect(row).toContainText("0.00 km");
  await expect(page.getByText(/has been completed successfully/)).toBeVisible();
  await expect(page.locator('.leaflet-overlay-pane path[fill="#1EAA55"]')).toHaveCount(0);
  await page.locator(".destination-flag").click();
  await expect(page.getByText("Destination Reached: Tracking Destination")).toBeVisible();
  await page.screenshot({path:"test-results/tracking-completed.png",fullPage:true});
  expect(errors).toEqual([]);
});
